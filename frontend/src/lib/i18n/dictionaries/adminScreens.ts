/**
 * Every string the fifteen back-office screens put in front of a human being.
 *
 * Same contract as `common.ts`: the French object is the shape, the Arabic one
 * is typed against it, and a key added on one side without the other breaks the
 * build instead of shipping a French sentence into an Arabic page.
 *
 * Two things this file needs that a flat dictionary does not, and which the
 * mapped type below allows without loosening that guarantee:
 *
 *   - sections nest one level (`news.deleteMessage`, `audit.actions.CREATE`),
 *     because five hundred strings in one flat object is not something anyone
 *     can read;
 *   - a few values are functions, for the places where a name, a count or a file
 *     size sits inside the sentence. An interpolation has to be a function so
 *     each language keeps control of its own word order.
 *
 * Dates and numbers are formatted here for the same reason: `toLocaleString`
 * with a hard-coded `'fr-FR'` is a French string in an Arabic page. Arabic uses
 * western digits here (620, not ٦٢٠) - `-u-nu-latn` asks for exactly that,
 * since Arabic's own default numbering is Arabic-Indic.
 */
type Translated<T> = {
  readonly [K in keyof T]: T[K] extends (...args: infer A) => string
    ? (...args: A) => string
    : T[K] extends string
      ? string
      : Translated<T[K]>;
};

